"""Backend-neutral seam only; no assembly backend is selected."""
from __future__ import annotations
from typing import Protocol,Mapping
class AssemblyAdapter(Protocol):
    def create_component(self,semantic_id:str,source_document:str)->str:...
    def publish_interface(self,component_id:str,interface_id:str,transform:Mapping[str,float])->None:...
    def place_by_interface(self,component_id:str,own_interface:str,target_component:str,target_interface:str)->None:...
    def ground(self,component_id:str)->None:...
    def create_fixed_relation(self,relation_id:str,first_interface:str,second_interface:str)->None:...
    def create_revolute_relation(self,relation_id:str,first_interface:str,second_interface:str,minimum_deg:float,maximum_deg:float)->None:...
    def degrees_of_freedom(self)->Mapping[str,int]:...
    def set_pose(self,angles:Mapping[str,float])->None:...
    def validate_interfaces(self)->tuple[str,...]:...
    def save_reopen(self,path:str)->bool:...
    def explode(self,distance_mm:float)->None:...
    def restore(self)->None:...
    def rollback(self,checkpoint_id:str)->bool:...
